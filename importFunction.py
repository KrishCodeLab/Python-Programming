# Why do we need import?
# Suppose you want to calculate the square root of a number. Python already provides a module called math with a sqrt() function
# import the entire module
import math

print(math.sqrt(25))

# import math loads the math module so you can access its functionality.
# math.sqrt(25) calls the sqrt() function from that module.
# The result is 5.0.

print(math.pi)
print(math.sqrt(16))
print(math.factorial(5))
